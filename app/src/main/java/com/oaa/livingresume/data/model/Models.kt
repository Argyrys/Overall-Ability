package com.oaa.livingresume.data.model

import kotlinx.serialization.Serializable

/**
 * The four OAA evaluation pillars and their weights.
 * Every pillar is scored 0..100; the weighted sum is the Overall OAA score.
 */
enum class Pillar(
    val label: String,
    val short: String,
    val weight: Double,
    val colorValue: Long,
) {
    ACADEMIC("Academic Ability", "Academic", 0.35, 0xFF00E5FF),
    ADAPTABILITY("Adaptability & Practical Skills", "Adapt", 0.30, 0xFF6C63FF),
    SOCIAL("Social Contribution & Leadership", "Social", 0.20, 0xFFFFD54F),
    PHYSICAL("Physical & Consistency", "Fitness", 0.15, 0xFF3DDC97);

    val weightPercent: Int get() = (weight * 100).toInt()
}

/** 90+ A+, 80+ A, 70+ B+, 60+ B, 50+ C, 40+ D, below 40 E. */
enum class Grade(val label: String, val minScore: Double) {
    A_PLUS("A+", 90.0),
    A("A", 80.0),
    B_PLUS("B+", 70.0),
    B("B", 60.0),
    C("C", 50.0),
    D("D", 40.0),
    E("E", 0.0),
}

/** Target job role used to personalise the OAA Quests. */
enum class TargetRole(val label: String) {
    SOFTWARE_ENGINEER("Software Engineer"),
    DATA_ANALYST("Data Analyst"),
    PRODUCT_MANAGER("Product Manager"),
    ML_ENGINEER("Machine Learning Engineer"),
}

enum class SemesterStatus { COMPLETED, ONGOING, UPCOMING }

enum class ProofStatus { PENDING, APPROVED, REJECTED }

@Serializable
data class Milestone(
    val title: String,
    val detail: String,
    val pillar: Pillar,
    val verified: Boolean = true,
    val date: String = "",
)

@Serializable
data class SemesterEntry(
    val semester: Int,
    val term: String,
    val gpa: Double,
    val pillarScores: Map<Pillar, Double> = emptyMap(),
    val milestones: List<Milestone> = emptyList(),
    val status: SemesterStatus = SemesterStatus.UPCOMING,
    val note: String = "",
)

@Serializable
data class SkillBadge(
    val title: String,
    val subtitle: String,
    val pillar: Pillar,
    val verified: Boolean = true,
)

@Serializable
data class Student(
    val id: String,
    val name: String,
    val rollNo: String,
    val branch: String,
    val college: String,
    val gradYear: Int,
    val targetRole: TargetRole,
    val email: String,
    val slug: String,
    val cgpa: Double,
    val pillarScores: Map<Pillar, Double>,
    val badges: List<SkillBadge> = emptyList(),
    val semesters: List<SemesterEntry> = emptyList(),
    val optedInPublic: Boolean = false,
    val headline: String = "",
    val skills: List<String> = emptyList(),
    val github: String = "",
    val linkedin: String = "",
)

@Serializable
data class ProofSubmission(
    val id: String,
    val studentId: String,
    val studentName: String,
    val title: String,
    val link: String,
    val pillar: Pillar,
    val points: Int,
    val status: ProofStatus = ProofStatus.PENDING,
    val submittedAt: String = "",
    val attachment: String? = null,
    val verifierNote: String? = null,
)

/** An actionable, role-mapped improvement quest generated by [com.oaa.livingresume.engine.OaaEngine]. */
data class Quest(
    val id: String,
    val title: String,
    val detail: String,
    val pillar: Pillar,
    val points: Int,
    val upgradeFrom: Grade,
    val upgradeTo: Grade,
    val tierUpgrade: Boolean,
    val targetRole: TargetRole,
)

/** Everything the private Improve screen needs, computed in one place. */
data class ImprovementPlan(
    val weakestPillar: Pillar,
    val weakestScore: Double,
    val weakestGrade: Grade,
    val pointsToNextTier: Double,
    val nextTierGrade: Grade?,
    val overallScore: Double,
    val overallGrade: Grade,
    val overallPointsToNextTier: Double,
    val nextOverallGrade: Grade?,
    val quests: List<Quest>,
)
